# ─── ICM OUTCOME UPDATE ────────────────────────────────────────────

def update_icm_outcome(outcome: str, cycle_id: Optional[str] = None):
    """Update the ICM reflection with a trade outcome (win/loss/neutral).

    Call this externally when trade results come in.
    Updates the latest un-outcomed ICM entry.
    """
    icm_file = BRAIN_DIR / "icm-reflection.latest.json"
    if not icm_file.exists():
        print("  No ICM reflection to update")
        return False

    try:
        with open(icm_file) as f:
            ref = json.load(f)
    except Exception:
        return False

    ref["outcome"] = outcome
    with open(icm_file, "w") as f:
        json.dump(ref, f, indent=2)

    # Also update in history
    old_icm_file = BRAIN_DIR / "icm-history.jsonl"
    if old_icm_file.exists():
        entries = []
        try:
            with open(old_icm_file) as f:
                for line in f:
                    line = line.strip()
                    if line:
                        try:
                            entry = json.loads(line)
                            if entry.get("outcome") is None:
                                if cycle_id is None or entry.get("cycle_id") == cycle_id:
                                    entry["outcome"] = outcome
                            entries.append(entry)
                        except json.JSONDecodeError:
                            entries.append({"raw": line})
        except Exception:
            pass

        with open(old_icm_file, "w") as f:
            for entry in entries:
                f.write(json.dumps(entry) + "\n")

    print(f"     ICM outcome updated: {outcome}")
    return True


# ─── FULL CYCLE ────────────────────────────────────────────────────

def run_cycle(advisory_only: bool = False) -> dict:
    """
    One complete brain consciousness cycle.
    1. Sensory cortex ingests ALL inputs
    2. Hippocampus recalls similar past states
    3. Load ICM reflection (last decision outcome)
    4. Proprioception: load current positions (GOLD #1 position awareness)
    5. Association cortex builds integrated awareness (with position modulation)
    6. Motor cortex executes decisions
    7. Write awareness for other agents
    8. Store ICM reflection for next cycle
    """
    ensure_dirs()
    start = time.time()

    print(f"\n  🧠 BRAIN CONSCIOUSNESS CYCLE — {datetime.now(timezone.utc).strftime('%H:%M:%S')} UTC")

    # Step 1: Sensory ingestion (parallel)
    sensory = ingest_all_signals()
    print(f"     Sensory: {sensory['active_count']}/{sensory['total_count']} signals active, "
          f"fused dir={sensory['fused_direction']:.3f}")
    if sensory.get("top_signals"):
        print(f"     Top signals: {', '.join(sensory['top_signals'])}")

    # Step 2: Memory recall
    memory = Hippocampus()
    similar = memory.recall_similar(sensory)
    print(f"     Memory: {len(similar)} similar past states recalled (novelty={1.0 - len(similar)/5:.2f})")

    # Step 2b: Load ICM reflection (last decision + outcome)
    icm_file = BRAIN_DIR / "icm-reflection.latest.json"
    icm_reflection = None
    if icm_file.exists():
        try:
            with open(icm_file) as f:
                icm_reflection = json.load(f)
            print(f"     ICM: Last action='{icm_reflection.get('action', '?')}' "
                  f"outcome='{icm_reflection.get('outcome', '?')}'")
        except Exception:
            pass

    # Step 2c: Proprioception — load position awareness (GOLD #1)
    proprioception = load_position_state()
    if proprioception.get("has_positions"):
        pos_str = ", ".join(
            f"{v['qty']} {k} {v['side'].upper()}"
            for k, v in proprioception.get("position_map", {}).items()
        )
        print(f"     Proprioception: Active positions — {pos_str}")
    elif proprioception.get("daily_trade_count", 0) > 0:
        print(f"     Proprioception: No positions today. "
              f"Daily: {proprioception['daily_trade_count']} trades, "
              f"PnL={proprioception['nq_daily_pnl']:+.2f}, "
              f"{proprioception['consecutive_losses']} consecutive losses")
    else:
        print(f"     Proprioception: No active positions")

    # Step 3: Association (build awareness with ICM reflection + proprioception)
    awareness = build_awareness(sensory, memory, proprioception=proprioception,
                                icm_reflection=icm_reflection)
    print(f"     Association: {len(awareness['attention'])} attention items, "
          f"{len(awareness['warnings'])} warnings")
    if awareness.get("icm_reflection"):
        print(f"     ICM reflection: {awareness['icm_reflection'].get('outcome', 'none')}")

    # Step 4: Motor execution
    motor_result = execute_decisions(awareness, memory, advisory_only=advisory_only)
    print(f"     Motor: {motor_result['executed']} decisions executed")

    # Step 5: Write awareness
    summary = write_awareness_summary(awareness)

    # Step 6: Store ICM reflection for next cycle
    # This keeps a rolling window of the last few decisions
    icm_entries = []
    old_icm_file = BRAIN_DIR / "icm-history.jsonl"
    if old_icm_file.exists():
        try:
            with open(old_icm_file) as f:
                for line in f:
                    line = line.strip()
                    if line:
                        try:
                            icm_entries.append(json.loads(line))
                        except json.JSONDecodeError:
                            pass
        except Exception:
            pass

    # Add this cycle's decision
    for dec in awareness.get("decisions", []):
        icm_entry = {
            "ts": awareness["ts"],
            "cycle_id": datetime.now(timezone.utc).strftime("cycle_%Y%m%d_%H%M%S"),
            "action": dec.get("action", ""),
            "priority": dec.get("priority", ""),
            "pathway": dec.get("pathway", ""),
            "fused_direction": sensory.get("fused_direction", 0),
            "top_signals": sensory.get("top_signals", []),
            "regime": awareness["regime"].get("regime", "unknown"),
            "outcome": None,  # Will be filled when trade result arrives
        }
        icm_entries.append(icm_entry)

    # Keep only last ICM_MAX_MEMORY entries
    icm_entries = icm_entries[-ICM_MAX_MEMORY:]

    # Write latest reflection (most recent decision)
    if icm_entries:
        with open(icm_file, "w") as f:
            json.dump(icm_entries[-1], f, indent=2)

    # Append to history
    with open(old_icm_file, "w") as f:
        for entry in icm_entries:
            f.write(json.dumps(entry) + "\n")

    # Save cycle
    cycle_id = datetime.now(timezone.utc).strftime("cycle_%Y%m%d_%H%M%S")
    cycle_file = BRAIN_DIR / "cycles" / f"{cycle_id}.json"
    with open(cycle_file, "w") as f:
        json.dump({
            "ts": sensory["ts"],
            "sensory": {k: v for k, v in sensory.items()
                        if k in ("active_count", "total_count", "fused_direction",
                                 "top_signals", "signal_attribution")},
            "awareness_summary": summary,
            "decisions": awareness["decisions"],
            "icm_reflection": icm_reflection,
            "musa_pathway_modulation": {
                "pathway_weights": awareness["pathway_weights"],
            },
            "duration_s": round(time.time() - start, 2),
            "advisoryOnly": advisory_only,
            "motor_result": motor_result,
            "researchOnly": True,
            "writesOrders": False,
            "touchesBroker": False,
        }, f, indent=2)

    # Also write current brain state
    brain_state_file = BRAIN_DIR / "brain-state.latest.json"
    with open(brain_state_file, "w") as f:
        json.dump({
            "ts": sensory["ts"],
            "cycle_id": cycle_id,
            "fused_direction": sensory["fused_direction"],
            "entropy_weighted": True,
            "active_signals": sensory["active_count"],
            "top_signals": sensory.get("top_signals", []),
            "regime": awareness["regime"],
            "novelty": awareness["memory"]["novelty_score"],
            "pathway_weights": awareness["pathway_weights"],
            "icm_reflection": icm_reflection,
            "proprioception": _summarize_proprioception(
                awareness.get("proprioception")
            ),
            "researchOnly": True,
            "writesOrders": False,
            "touchesBroker": False,
            "tradable_signal": False,
            "promoted_for_execution": False,
            "readyForExecution": False,
            "execution_role": "diagnostic_only",
            "advisoryOnly": advisory_only,
            "attention": awareness["attention"][:3],
            "decisions": awareness["decisions"][:3],
            "warnings": awareness["warnings"],
        }, f, indent=2)

    print(f"     Cycle complete in {time.time()-start:.1f}s")

    return awareness


