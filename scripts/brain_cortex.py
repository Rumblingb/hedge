def cmd_daemon():
    """Continuous mode — runs every 30 minutes."""
    print(f"\n  🧠 BRAIN DAEMON STARTED — running every 30m in advisory-only mode")
    print(f"     Press Ctrl+C to stop\n")

    while True:
        run_cycle(advisory_only=True)
        print(f"\n  💤 Sleeping 30 minutes...")
        time.sleep(1800)


def main():
    import argparse
    parser = argparse.ArgumentParser(
        description="🧠 Brain Cortex — Central consciousness for the trading system"
    )
    parser.add_argument("action", nargs="?", default="cycle",
                        choices=["cycle", "daemon", "status", "awareness", "regions",
                                 "update-outcome", "memory"],
                        help="Brain action (default: cycle)")
    parser.add_argument("--outcome", type=str, default=None,
                        help="Outcome for update-outcome: win/loss/neutral")
    parser.add_argument("--cycle-id", type=str, default=None,
                        help="Cycle ID for update-outcome")
    parser.add_argument("--regime", type=str, default=None,
                        help="Regime filter for memory query")
    parser.add_argument("--signal", type=str, default=None,
                        help="Signal filter for memory query")
    parser.add_argument("--limit", type=int, default=5,
                        help="Limit for memory query")
    parser.add_argument("--advisory-only", action="store_true",
                        help="Refresh brain state without writing motor/urgent execution outputs")

    args = parser.parse_args()

    if args.action == "cycle":
        cmd_cycle(advisory_only=args.advisory_only)
    elif args.action == "daemon":
        cmd_daemon()
    elif args.action == "status":
        cmd_status()
    elif args.action == "awareness":
        cmd_awareness()
    elif args.action == "regions":
        print(f"\n{'='*60}")
        print(f"  🧠 BRAIN REGIONS")
        print(f"{'='*60}")
        for region_id, region in BRAIN_REGIONS.items():
            print(f"\n  [{region_id}]")
            print(f"     Name: {region['name']}")
            print(f"     Function: {region['function']}")
            if "inputs" in region:
                print(f"     Inputs ({len(region['inputs'])}):")
                for inp in region["inputs"]:
                    print(f"       - {inp['id']} ({inp['type']})")
            if "modules" in region:
                for m in region["modules"]:
                    print(f"       - {m}")
            if "outputs" in region:
                print(f"     Outputs:")
                for o in region["outputs"]:
                    print(f"       → {o}")
        print()
    elif args.action == "memory":
        memory = Hippocampus()
        limit = args.limit or 5
        if args.regime:
            results = memory.query_by_regime(args.regime, limit)
        elif args.outcome:
            results = memory.query_by_outcome(args.outcome, limit)
        elif args.signal:
            results = memory.query_by_signal(args.signal, limit)
        else:
            results = memory.memories[-limit:]
        print(f"\n  🧠 HIPPOCAMPUS QUERY: {len(results)} memories")
        for m in results[-5:]:
            mem_id = m.get("memory_id", "?")[:8]
            regime = m.get("regime", "?")
            if isinstance(regime, dict):
                regime = regime.get("regime", "?")
            fd = m.get("fused_direction", 0)
            outcome = m.get("outcome", "?")
            ts = m.get("ts", "")[:16] if m.get("ts") else "?"
            top = m.get("top_signals", [])
            print(f"     [{mem_id}] {ts} | regime={regime} | dir={fd:+.2f} | outcome={outcome}")
            if top:
                print(f"            signals: {', '.join(top[:3])}")
    elif args.action == "update-outcome":
        if not args.outcome:
            print("  Usage: python3 scripts/brain_cortex.py update-outcome --outcome win|loss|neutral [--cycle-id <id>]")
            return
        if args.outcome not in ("win", "loss", "neutral"):
            print(f"  Invalid outcome: {args.outcome}. Use win/loss/neutral.")
            return
        update_icm_outcome(args.outcome, args.cycle_id)


if __name__ == "__main__":
    main()
