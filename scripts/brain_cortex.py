def ingest_all_signals() -> dict[str, Any]:
    """Read ALL signal state files simultaneously. Returns a unified sensory map."""
    sensory = {
        "ts": datetime.now(timezone.utc).isoformat(),
        "signals": {},
        "active_count": 0,
        "total_count": 0,
        "direction_signals": {},  # direction per signal (bullish/bearish/neutral)
        "fused_direction": 0.0,   # -1 to +1
        "regime": "unknown",
        "volatility": "unknown",
        "novel_items": [],
        "warnings": [],
    }

    regions = sensory_inputs()
    sensory["configured_static_count"] = len(BRAIN_REGIONS["sensory_cortex"]["inputs"])
    sensory["dynamic_discovered_count"] = max(0, len(regions) - sensory["configured_static_count"])
    for inp in regions:
        src = inp["source"]
        if not src.exists():
            continue

        try:
            with open(src) as f:
                data = json.load(f)
        except Exception:
            continue

        signal_id = inp["id"]
        stat = src.stat()
        age_seconds = time.time() - stat.st_mtime
        ttl_seconds = SIGNAL_TTL_SECONDS.get(signal_id, DEFAULT_SIGNAL_TTL_SECONDS)
        is_fresh = age_seconds <= ttl_seconds

        # Extract direction. Stale files are retained for diagnostics but are
        # neutralized before fusion so old weekend/holiday outputs cannot fire
        # motor decisions.
        try:
            raw_direction = _extract_direction(signal_id, data)
        except Exception as exc:
            raw_direction = None
            sensory["warnings"].append(f"SIGNAL PARSE ERROR: {signal_id} direction error={exc}")
        direction = raw_direction if is_fresh else None

        # Extract entropy for confidence weighting
        try:
            entropy = _extract_entropy(signal_id, data)
        except Exception as exc:
            entropy = None
            sensory["warnings"].append(f"SIGNAL PARSE ERROR: {signal_id} entropy error={exc}")
        # If entropy unavailable, default to neutral (0.5)
        if entropy is None:
            entropy = 0.5

        # Apply entropy-adjusted confidence: C = ε + (1-ε)(1-H)
        confidence = ENTROPY_EPSILON + (1.0 - ENTROPY_EPSILON) * (1.0 - entropy)
        if not is_fresh:
            confidence = 0.0
            sensory["warnings"].append(
                f"STALE SIGNAL: {signal_id} age={age_seconds/3600:.1f}h ttl={ttl_seconds/3600:.1f}h ignored"
            )

        sensory["signals"][signal_id] = {
            "type": inp["type"],
            "data": data,
            "fresh": stat.st_mtime,
            "age_seconds": round(age_seconds, 1),
            "ttl_seconds": ttl_seconds,
            "is_fresh": is_fresh,
            "direction": direction,
            "raw_direction": raw_direction,
            "entropy": round(entropy, 3),
            "confidence": round(confidence, 3),
        }
        sensory["total_count"] += 1
        if is_fresh:
            sensory["active_count"] += 1

        if direction is not None:
            sensory["direction_signals"][signal_id] = {
                "direction": direction,
                "confidence": confidence,
                "entropy": entropy,
            }

    # Compute entropy-weighted fused direction (MuSA principle)
    # Instead of simple average: Σ (direction_i × confidence_i) / Σ confidence_i
    dir_entries = sensory["direction_signals"]
    if dir_entries:
        weighted_sum = sum(
            e["direction"] * e["confidence"]
            for e in dir_entries.values()
        )
        total_confidence = sum(e["confidence"] for e in dir_entries.values())
        if total_confidence > 0:
            sensory["fused_direction"] = weighted_sum / total_confidence
        else:
            sensory["fused_direction"] = 0.0

        # Store per-signal attribution score (softmax of confidence-weighted)
        attribution_weights = {}
        for sid, entry in dir_entries.items():
            attribution_weights[sid] = abs(entry["direction"]) * entry["confidence"]
        total_attribution = sum(attribution_weights.values()) or 1.0
        sensory["signal_attribution"] = {
            sid: round(w / total_attribution, 4)
            for sid, w in sorted(
                attribution_weights.items(), key=lambda x: x[1], reverse=True
            )
        }
        sensory["top_signals"] = list(sensory["signal_attribution"].keys())[:3]

    return sensory


def _extract_entropy(signal_id: str, data: dict) -> Optional[float]:
    """Extract entropy (uncertainty) from signal data.
    
    Returns None if entropy can't be determined (default to neutral).
    0.0 = completely certain, 1.0 = maximally uncertain.
    """
    if not isinstance(data, dict):
        return None

    # Direct entropy/confidence fields
    if "entropy" in data:
        e = data["entropy"]
        if isinstance(e, (int, float)):
            return max(0.0, min(1.0, float(e)))
    if "confidence" in data:
        c = data["confidence"]
        if isinstance(c, (int, float)):
            # confidence=1.0 → entropy=0.0, confidence=0.0 → entropy=1.0
            return max(0.0, min(1.0, 1.0 - float(c)))

    # Arbitration format — has final_signal_conf
    if "final_signal_conf" in data:
        c = data["final_signal_conf"]
        if isinstance(c, (int, float)):
            return max(0.0, min(1.0, 1.0 - float(c)))

    # Whale flow — has confidence
    if "confidence" in data:
        c = data["confidence"]
        if isinstance(c, (int, float)):
            return max(0.0, min(1.0, 1.0 - float(c)))

    # Noise analysis (direct noise regime metric)
    if signal_id == "noise":
        nsr = data.get("nq_nsr", data.get("nsr", None))
        if nsr is not None and isinstance(nsr, (int, float)):
            # NSR 0-12 → low noise (low entropy), NSR 40+ → extreme (high entropy)
            return max(0.0, min(1.0, float(nsr) / 50.0))

    return None


def _extract_direction(signal_id: str, data: dict) -> Optional[float]:
    """Extract signal direction (-1 to +1) from various signal formats."""
    if not isinstance(data, dict):
        return None

    # Standardized arbitration format
    if "final_dir" in data:
        return data.get("final_dir", 0)

    # Insider format
    if "nq_bias" in data:
        bias = data["nq_bias"]
        return 1.0 if "bullish" in str(bias).lower() else -1.0 if "bearish" in str(bias).lower() else 0.0

    # COT format
    markets = data.get("markets")
    if isinstance(markets, dict) and "NQ" in markets:
        nq = markets["NQ"]
        if isinstance(nq, dict):
            dir_val = nq.get("direction", 0)
            return float(dir_val) if isinstance(dir_val, (int, float)) else 0.0

    # VWAP format
    if "NQ" in data and isinstance(data["NQ"], dict):
        dir_str = data["NQ"].get("direction", "neutral")
        return 1.0 if "long" in str(dir_str).lower() else -1.0 if "short" in str(dir_str).lower() else 0.0

    # Kalman format
    strat = data.get("strategy", "")
    if strat == "ENTRY_LONG":
        return 0.6
    elif strat == "ENTRY_SHORT":
        return -0.6
    elif strat == "EXIT":
        return 0.0
    elif strat == "HOLD":
        return 0.3 if data.get("direction", "").lower() == "long" else -0.3

    # Whale flow
    dir_val = data.get("direction", "neutral")
    conf = float(data.get("confidence", 0.5))
    if "bullish" in str(dir_val).lower():
        return 1.0 * conf
    elif "bearish" in str(dir_val).lower():
        return -1.0 * conf

    # GOLD #6: PM Arbitrage Scanner — total_found > 0 = crypto opportunity
    if signal_id == "pm_arb":
        found = data.get("total_found", 0)
        edge = data.get("max_edge_pct", 0)
        if found > 0 and edge > 0:
            return min(0.4, edge / 100)
        return 0.0

    # GOLD #7: NLP Sentiment — direct -1..+1 field
    if signal_id == "sentiment":
        s = data.get("sentiment", 0)
        return max(-1.0, min(1.0, float(s)))

    # GOLD #9: Macro Trend Overlay — direct -1..+1 macro_direction
    if signal_id == "macro":
        md = data.get("macro_direction", 0)
        conf = data.get("confidence", 0.5)
        return max(-1.0, min(1.0, float(md))) * float(conf)

    # GOLD #10: Alt Data Bridge — direct -1..+1 macro_signal
    if signal_id == "alt_data":
        ms = data.get("macro_signal", 0)
        return max(-1.0, min(1.0, float(ms)))

    # GOLD #11: Dealer Gamma Signal — direct -1..+1 gamma_signal
    if signal_id == "gamma":
        gs = data.get("gamma_signal", 0)
        return max(-1.0, min(1.0, float(gs)))

    # Delta Dislocation — divergence between price and cumulative delta
    if signal_id == "delta_dislocation":
        ds = data.get("delta_signal", 0)
        return max(-1.0, min(1.0, float(ds)))

    # General direction field
    if "direction" in data:
        d = data["direction"]
        if isinstance(d, (int, float)):
            return float(d)

    return None


def check_market_regime() -> dict[str, Any]:
    """Determine current market regime from signals and calendar."""
    regime = {
        "regime": "unknown",
        "confidence": 0.0,
        "opening_type": "unknown",
        "vix_level": None,
        "day_of_week": datetime.now(timezone.utc).strftime("%A"),
        "is_market_open": False,
        "reason": "",
    }

    # Check opening candle classifier
    oc_file = STATE_DIR / "opening-candle-signal.latest.json"
    if oc_file.exists():
        try:
            with open(oc_file) as f:
                od = json.load(f)
            regime["opening_type"] = od.get("session_type", od.get("type", "unknown"))
            regime["regime"] = regime["opening_type"]
            regime["reason"] += f"opening_candle={regime['opening_type']} "
        except Exception:
            pass

    # Check noise analysis
    na_file = STATE_DIR / "noise-analysis.latest.json"
    if na_file.exists():
        try:
            with open(na_file) as f:
                nd = json.load(f)
            regime["volatility"] = nd.get("nq_noise_regime", nd.get("regime", "unknown"))
            regime["reason"] += f"noise={regime['volatility']} "
        except Exception:
            pass

    # Day of week context
    dow = regime["day_of_week"]
    if dow in ("Saturday", "Sunday"):
        regime["is_market_open"] = False
        regime["regime"] = "weekend"
    else:
        regime["is_market_open"] = True

    return regime


