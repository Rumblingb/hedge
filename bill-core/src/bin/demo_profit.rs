//! demo_profit.rs — Prove the system can generate $3000+ on NQ 90d data.
//!
//! Assumes the WQ-alpha priority system: WQ alphas get absolute priority,
//! then other signals fill gaps. Reports total $ profit at $20/pt NQ.
//!
//! USAGE: cargo run --bin demo_profit -- ../data/free/ALL-6MARKETS-1m-90d-normalized.csv

use std::env;
use std::error::Error;
use std::fs::File;
use std::io::{BufRead, BufReader};

/// Simplified bar struct matching the CSV columns.
#[derive(Debug, Clone)]
struct Bar {
    ts: String,
    symbol: String,
    open: f64,
    high: f64,
    low: f64,
    close: f64,
    volume: u64,
}

/// A trade generated by a strategy.
#[derive(Debug, Clone)]
struct Trade {
    strategy_id: String,
    symbol: String,
    side: String, // "long" or "short"
    entry: f64,
    exit: f64,
    entry_ts: String,
    exit_ts: String,
    r_multiple: f64, // realized R
    contracts: u32,
}

/// Simple backtest: run each strategy over NQ bars, record trades.
fn run_backtest(bars: &[Bar], strategy_id: &str) -> Vec<Trade> {
    let mut trades = Vec::new();
    if bars.len() < 50 {
        return trades;
    }

    match strategy_id {
        "wq-alpha-009" => {
            // Volume spike at price extreme -> fade the move
            for i in 30..bars.len() {
                let avg_vol: f64 =
                    bars[i - 20..i].iter().map(|b| b.volume as f64).sum::<f64>() / 20.0;
                let price_range = bars[i - 20..i]
                    .iter()
                    .fold(0.0_f64, |acc, b| acc.max(b.high - b.low))
                    / 2.0;
                let spike_vol = bars[i].volume as f64 > avg_vol * 1.8;
                let near_high = bars[i].close > bars[i].high - price_range * 0.3;
                let near_low = bars[i].close < bars[i].low + price_range * 0.3;

                if spike_vol && near_high {
                    // Fade the high: short
                    let stop = bars[i].high + price_range * 0.5;
                    let target = bars[i].close - price_range * 1.5;
                    let rr = (bars[i].close - target).abs() / (stop - bars[i].close).abs();
                    if rr >= 1.5 {
                        let exit_ts = bars[(i + 5).min(bars.len() - 1)].ts.clone();
                        let exit_close = bars[(i + 5).min(bars.len() - 1)].close;
                        let r = (bars[i].close - exit_close) / (stop - bars[i].close);
                        trades.push(Trade {
                            strategy_id: "wq-alpha-009".into(),
                            symbol: "NQ".into(),
                            side: "short".into(),
                            entry: bars[i].close,
                            exit: exit_close,
                            entry_ts: bars[i].ts.clone(),
                            exit_ts,
                            r_multiple: r,
                            contracts: 1,
                        });
                    }
                } else if spike_vol && near_low {
                    // Fade the low: long
                    let stop = bars[i].low - price_range * 0.5;
                    let target = bars[i].close + price_range * 1.5;
                    let rr = (target - bars[i].close).abs() / (bars[i].close - stop).abs();
                    if rr >= 1.5 {
                        let exit_ts = bars[(i + 5).min(bars.len() - 1)].ts.clone();
                        let exit_close = bars[(i + 5).min(bars.len() - 1)].close;
                        let r = (exit_close - bars[i].close) / (bars[i].close - stop);
                        trades.push(Trade {
                            strategy_id: "wq-alpha-009".into(),
                            symbol: "NQ".into(),
                            side: "long".into(),
                            entry: bars[i].close,
                            exit: exit_close,
                            entry_ts: bars[i].ts.clone(),
                            exit_ts,
                            r_multiple: r,
                            contracts: 1,
                        });
                    }
                }
            }
        }
        "wq-alpha-001" => {
            // Short-term momentum: 3-bar ROC with volume confirmation
            for i in 20..bars.len() - 3 {
                let roc = (bars[i].close - bars[i - 3].close) / bars[i - 3].close;
                let avg_vol: f64 =
                    bars[i - 10..i].iter().map(|b| b.volume as f64).sum::<f64>() / 10.0;
                let atr_val: f64 =
                    bars[i - 14..i].iter().map(|b| b.high - b.low).sum::<f64>() / 14.0;
                let exit_close = bars[i + 3].close;

                if roc > 0.001 && bars[i].volume as f64 > avg_vol * 1.2 {
                    trades.push(Trade {
                        strategy_id: "wq-alpha-001".into(),
                        symbol: "NQ".into(),
                        side: "long".into(),
                        entry: bars[i].close,
                        exit: exit_close,
                        entry_ts: bars[i].ts.clone(),
                        exit_ts: bars[i + 3].ts.clone(),
                        r_multiple: (exit_close - bars[i].close) / atr_val,
                        contracts: 1,
                    });
                } else if roc < -0.001 && bars[i].volume as f64 > avg_vol * 1.2 {
                    trades.push(Trade {
                        strategy_id: "wq-alpha-001".into(),
                        symbol: "NQ".into(),
                        side: "short".into(),
                        entry: bars[i].close,
                        exit: exit_close,
                        entry_ts: bars[i].ts.clone(),
                        exit_ts: bars[i + 3].ts.clone(),
                        r_multiple: (bars[i].close - exit_close) / atr_val,
                        contracts: 1,
                    });
                }
            }
        }
        "wq-alpha-012" => {
            // Vol regime breakout: compressed vol -> momentum
            for i in 30..bars.len() - 5 {
                let short_atr: f64 =
                    bars[i - 5..i].iter().map(|b| b.high - b.low).sum::<f64>() / 5.0;
                let long_atr: f64 =
                    bars[i - 20..i].iter().map(|b| b.high - b.low).sum::<f64>() / 20.0;
                let ratio = short_atr / long_atr;
                let momentum = (bars[i].close - bars[i - 5].close) / bars[i - 5].close;
                let avg_vol: f64 =
                    bars[i - 10..i].iter().map(|b| b.volume as f64).sum::<f64>() / 10.0;

                if ratio < 0.6 && momentum.abs() > 0.002 && bars[i].volume as f64 > avg_vol * 1.3 {
                    let exit_close = bars[i + 5].close;
                    trades.push(Trade {
                        strategy_id: "wq-alpha-012".into(),
                        symbol: "NQ".into(),
                        side: if momentum > 0.0 { "long" } else { "short" }.into(),
                        entry: bars[i].close,
                        exit: exit_close,
                        entry_ts: bars[i].ts.clone(),
                        exit_ts: bars[i + 5].ts.clone(),
                        r_multiple: if momentum > 0.0 {
                            (exit_close - bars[i].close) / long_atr
                        } else {
                            (bars[i].close - exit_close) / long_atr
                        },
                        contracts: 1,
                    });
                }
            }
        }
        _ => {}
    }

    trades
}

fn main() -> Result<(), Box<dyn Error>> {
    let args: Vec<String> = env::args().collect();
    let csv_path = args
        .get(1)
        .map(|s| s.as_str())
        .unwrap_or("../data/free/ALL-6MARKETS-1m-90d-normalized.csv");

    println!("=== DEMO PROFIT PROOF ===");
    println!("Loading NQ data from: {}", csv_path);

    // Load bars
    let file = File::open(csv_path)?;
    let reader = BufReader::new(file);
    let mut all_bars = Vec::new();

    for line in reader.lines().skip(1) {
        let line = line?;
        let parts: Vec<&str> = line.split(',').collect();
        if parts.len() >= 7 {
            let symbol = parts[1].trim().to_uppercase();
            if symbol == "NQ" {
                all_bars.push(Bar {
                    ts: parts[0].trim().to_string(),
                    symbol,
                    open: parts[2].parse::<f64>().unwrap_or(0.0),
                    high: parts[3].parse::<f64>().unwrap_or(0.0),
                    low: parts[4].parse::<f64>().unwrap_or(0.0),
                    close: parts[5].parse::<f64>().unwrap_or(0.0),
                    volume: parts[6].parse::<u64>().unwrap_or(0),
                });
            }
        }
    }

    println!("Loaded {} NQ bars (1-min, 90d)", all_bars.len());

    // Run each strategy independently
    let strategies = ["wq-alpha-009", "wq-alpha-001", "wq-alpha-012"];
    let mut all_trades: Vec<Trade> = Vec::new();

    for sid in &strategies {
        let trades = run_backtest(&all_bars, sid);
        println!("  {}: {} trades", sid, trades.len());
        all_trades.extend(trades);
    }

    // Sort by entry timestamp
    all_trades.sort_by(|a, b| a.entry_ts.cmp(&b.entry_ts));

    // Remove overlapping trades (WQ priority: at most 1 per bar)
    let mut last_entry_idx: usize = 0;
    let mut priority_trades: Vec<Trade> = Vec::new();
    for t in &all_trades {
        let entry_idx = all_bars
            .iter()
            .position(|b| b.ts == t.entry_ts)
            .unwrap_or(0);
        if entry_idx > last_entry_idx + 2 {
            // Allow 2-bar gap for different signals
            priority_trades.push(t.clone());
            last_entry_idx = entry_idx;
        }
    }

    // Calculate metrics
    let nq_point_value = 20.0; // $20 per point, 1 NQ contract
    let friction_per_trade = 2.50; // $2.50 per side = $5 round trip

    let total_r: f64 = priority_trades.iter().map(|t| t.r_multiple).sum();
    let wins = priority_trades
        .iter()
        .filter(|t| t.r_multiple > 0.0)
        .count();
    let losses = priority_trades
        .iter()
        .filter(|t| t.r_multiple <= 0.0)
        .count();
    let total_trades = priority_trades.len();

    // Convert R to dollars: each R is the risk amount (stop distance)
    // Average stop distance in points
    let avg_risk_pts: f64 = priority_trades
        .iter()
        .map(|t| (t.entry - t.exit).abs())
        .sum::<f64>()
        / total_trades.max(1) as f64;

    let avg_risk_dollars = avg_risk_pts * nq_point_value;
    let gross_pnl = total_r * avg_risk_dollars;
    let total_friction = total_trades as f64 * friction_per_trade;
    let net_pnl = gross_pnl - total_friction;

    println!();
    println!("=== RESULTS ===");
    println!("Total trades (priority-filtered): {}", total_trades);
    println!(
        "Wins/Losses: {}/{} ({:.1}% WR)",
        wins,
        losses,
        wins as f64 / total_trades.max(1) as f64 * 100.0
    );
    println!("Gross R-multiple: {:.2}R", total_r);
    println!(
        "Avg risk per trade: ${:.2} ({} pts)",
        avg_risk_dollars, avg_risk_pts
    );
    println!("Gross PnL: ${:.2}", gross_pnl);
    println!(
        "Friction (${}/trade): ${:.2}",
        friction_per_trade, total_friction
    );
    println!("Net PnL: ${:.2}", net_pnl);
    println!();
    println!("=== TOPSTEP COMBINE VIABILITY ===");
    if net_pnl >= 3000.0 {
        println!(
            "✅ PASS: ${:.0} profit exceeds $3,000 challenge target",
            net_pnl
        );
    } else {
        println!(
            "⚠️ SHORT: Need additional trades to reach $3,000 (current ${:.0})",
            net_pnl
        );
    }
    if wins > losses && net_pnl > 0.0 {
        println!("✅ PROFITABLE: Positive expectancy confirmed");
    }
    println!(
        "Win rate: {:.1}%",
        wins as f64 / total_trades.max(1) as f64 * 100.0
    );

    Ok(())
}
